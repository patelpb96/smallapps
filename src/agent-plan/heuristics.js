/**
 * The heuristic catalog.
 *
 * A heuristic is a testable planning rule, not advice. Each one declares:
 *   when()        – relevance predicate over facts
 *   because()     – which facts made it relevant (rendered to the user)
 *   requirement() – what to build, in imperative voice
 *   verify()      – a check a reviewer or CI can actually run
 *
 * severity:
 *   'must'     – a gate. Ship without it and the plan is wrong.
 *   'should'   – strong default; deviate only with a written reason.
 *   'consider' – cheap if you do it now, expensive if you retrofit it.
 */

