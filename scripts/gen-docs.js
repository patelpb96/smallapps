#!/usr/bin/env node
/**
 * Generate reference docs from the source of truth.
 *
 *   node scripts/gen-docs.js           # write
 *   node scripts/gen-docs.js --check   # exit 1 if the committed docs are stale
 *
 * Docs that can drift are docs that lie. These two are derived, so they cannot.
 */

import { writeFile, readFile } from 'node:fs/promises';
import { join, resolve } from 'node:path';

import { HEURISTICS, CATEGORIES, SOURCES, QUESTIONS, GROUPS, PRESETS } from '../src/index.js';
import { AUTONOMY_TIERS, SANDBOX_TIERS } from '../src/tiers.js';

const ROOT = resolve(import.meta.dirname, '..');
const CHECK = process.argv.includes('--check');

const KIND_ORDER = ['standard', 'spec', 'framework', 'vendor-doc', 'paper', 'incident'];
const KIND_TITLE = {
  standard: 'Standards and regulatory material',
  spec: 'Specifications',
  framework: 'Frameworks and taxonomies',
  'vendor-doc': 'Vendor engineering guidance',
  paper: 'Papers',
  incident: 'Incident write-ups',
};

function heuristicsDoc() {
  const L = [];
  L.push('# Heuristic reference');
  L.push('');
  L.push('_Generated by `scripts/gen-docs.js` from `src/heuristics.js`. Do not edit by hand — edit the catalog and regenerate._');
  L.push('');
  L.push(`${HEURISTICS.length} rules across ${Object.keys(CATEGORIES).length} categories. Every rule names the facts that trigger it and a check a reviewer can actually run.`);
  L.push('');

  L.push('## Severity');
  L.push('');
  L.push('| | Meaning |');
  L.push('|---|---|');
  L.push('| **must** | A gate. Ship without it and the plan is wrong. |');
  L.push('| **should** | Strong default. Deviate only with a written reason. |');
  L.push('| **consider** | Cheap now, expensive to retrofit. |');
  L.push('');

  for (const [key, cat] of Object.entries(CATEGORIES)) {
    const items = HEURISTICS.filter((h) => h.category === key);
    if (!items.length) continue;
    L.push(`## ${cat.title}`);
    L.push('');
    L.push(`_${cat.blurb}_`);
    L.push('');
    for (const h of items) {
      L.push(`### ${h.id} — ${h.title}`);
      L.push('');
      L.push(`**${h.severity.toUpperCase()}**`);
      L.push('');
      L.push(h.requirement({}));
      L.push('');
      L.push(`**Verify:** ${h.verify}`);
      L.push('');
      if (h.antiPattern) {
        L.push(`**Anti-pattern:** ${h.antiPattern}`);
        L.push('');
      }
      L.push(`**Sources:** ${h.sources.map((s) => {
        const x = SOURCES[s];
        return `[${x.short || x.publisher} ${x.year}](${x.url})`;
      }).join(' · ')}`);
      L.push('');
    }
  }

  L.push('## Tier ladders');
  L.push('');
  L.push('### Autonomy');
  L.push('');
  L.push('| Tier | Name | Human role | Definition | Mappings |');
  L.push('|---|---|---|---|---|');
  for (const t of AUTONOMY_TIERS) {
    L.push(`| ${t.id} | ${t.name} | ${t.humanRole} | ${t.definition} | AWS: ${t.aws}; CSA: ${t.csa}; Knight: ${t.knight} |`);
  }
  L.push('');
  L.push('### Sandbox');
  L.push('');
  L.push('| Tier | Name | Provides |');
  L.push('|---|---|---|');
  for (const t of SANDBOX_TIERS) L.push(`| ${t.id} | ${t.name} | ${t.definition} |`);
  L.push('');

  L.push('## Intake questions');
  L.push('');
  L.push('| Group | id | Question | Type |');
  L.push('|---|---|---|---|');
  for (const g of GROUPS) {
    for (const q of QUESTIONS.filter((x) => x.group === g.id)) {
      L.push(`| ${g.title} | \`${q.id}\` | ${q.prompt} | ${q.type} |`);
    }
  }
  L.push('');
  L.push('## Presets');
  L.push('');
  for (const [key, p] of Object.entries(PRESETS)) L.push(`- \`${key}\` — ${p.label}`);
  L.push('');

  return L.join('\n');
}

function sourcesDoc() {
  const L = [];
  L.push('# Sources');
  L.push('');
  L.push('_Generated by `scripts/gen-docs.js` from `src/sources.js`. Do not edit by hand._');
  L.push('');
  L.push('Every heuristic in this tool cites at least one entry below. If something is not here, it does not get to be a recommendation. Papers listed with a local copy are checked into `docs/papers/`.');
  L.push('');

  for (const kind of KIND_ORDER) {
    const entries = Object.entries(SOURCES).filter(([, s]) => s.kind === kind);
    if (!entries.length) continue;
    L.push(`## ${KIND_TITLE[kind]}`);
    L.push('');
    for (const [, s] of entries) {
      L.push(`### ${s.title}`);
      L.push('');
      L.push(`${s.publisher} · ${s.year}`);
      L.push('');
      L.push(s.note || '');
      L.push('');
      L.push(`<${s.url}>${s.local ? ` · local: \`${s.local}\`` : ''}`);
      L.push('');
    }
  }

  L.push('## Reading order');
  L.push('');
  L.push('If you only read four things before designing an agent system:');
  L.push('');
  L.push('1. **AWS Agentic AI Security Scoping Matrix** — puts a name on how much agency you are actually granting, and what changes at each step.');
  L.push('2. **OWASP Top 10 for Agentic Applications 2026** — the failure catalogue, written for people shipping rather than reviewing.');
  L.push('3. **SandboxEscapeBench** — calibrates how much you should trust "it runs in a container".');
  L.push('4. **τ-bench** — explains why pass@1 flatters an agent and what pass^k measures instead.');
  L.push('');
  L.push('Then, depending on what you are building: **Anthropic\'s Building Effective AI Agents** for shape, **OWASP AISVS C09** for testable requirements, **NIST AI 600-1** for the risk register, and **Saber / Procedure-Aware Evaluation** for how to evaluate an agent that mutates state.');
  L.push('');

  return L.join('\n');
}

async function write(target, content) {
  const path = join(ROOT, target);
  if (CHECK) {
    let current = '';
    try { current = await readFile(path, 'utf8'); } catch { /* missing counts as stale */ }
    if (current !== content) {
      process.stderr.write(`stale: ${target} — run \`node scripts/gen-docs.js\`\n`);
      process.exitCode = 1;
    }
    return;
  }
  await writeFile(path, content, 'utf8');
  process.stdout.write(`wrote ${target}\n`);
}

await write('docs/HEURISTICS.md', heuristicsDoc());
await write('docs/SOURCES.md', sourcesDoc());

if (CHECK && process.exitCode !== 1) process.stdout.write('docs are current\n');
